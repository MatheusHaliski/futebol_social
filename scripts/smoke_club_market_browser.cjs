/* Requires Playwright and the private --session-file from smoke_club_market.py. */
const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const file=process.argv[2];if(!file)throw Error('Informe o arquivo temporário de sessões do smoke de API');
 const data=JSON.parse(fs.readFileSync(file,'utf8'));
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const errors=[];const checks=[];
 async function session(actor,viewport={width:1440,height:1000}){
  const context=await browser.newContext({viewport});
  await context.addInitScript(({access,refresh})=>{sessionStorage.setItem('fas.access',access);sessionStorage.setItem('fas.refresh',refresh);sessionStorage.removeItem('fas.demo');},{access:actor.accessToken,refresh:actor.refreshToken});
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));return {page,context};
 }
 let {page,context}=await session(data.outsider);
 await page.goto(data.base+'/#/buscar?entity=ATLETA&q='+data.prefix);
 await page.locator('#globalResults .cm-result').first().waitFor();
 await page.getByRole('button',{name:'Adicionar filtro',exact:true}).click();
 await page.locator('[data-field]').selectOption('athlete.transferSituation');
 const value=page.locator('[data-value]');
 if(await value.evaluate(el=>el.tagName)==='SELECT')await value.selectOption('FREE_AGENT');else await value.fill('FREE_AGENT');
 await page.getByRole('button',{name:'Buscar',exact:true}).click();
 await page.waitForFunction(()=>location.hash.includes('transferSituation'));
 await page.locator('#globalResults .cm-result').first().waitFor();
 checks.push('Busca global com filtro de situação de transferência');
 await page.screenshot({path:'/tmp/club-search-desktop.png',fullPage:true});
 await page.goto(data.base+'/#/clube?clubId='+data.clubId);
 await page.locator('#clubResources').waitFor();
 if(await page.locator('#clubResources').innerText().then(s=>s.includes('987654')))throw Error('Folha privada exposta no navegador');
 checks.push('Perfil público de clube com histórico, estádio e finanças autorizadas');
 await page.screenshot({path:'/tmp/club-profile-desktop.png',fullPage:true});
 await page.goto(data.base+'/#/vitrine?athleteId='+data.athleteId);
 await page.locator('#vtCompatibility form').waitFor();
 await page.locator('#vtCompatibility [name="search"]').fill(data.prefix);
 await page.waitForTimeout(500);
 await page.locator('#vtCompatibility [name="clubId"]').selectOption(data.clubId);
 await page.locator('#vtCompatibility [name="teamId"]').selectOption(data.teamId);
 await page.getByRole('button',{name:'Calcular compatibilidade',exact:true}).click();
 await page.locator('.cm-score').waitFor();
 if(!(await page.locator('.cm-score').innerText()).includes('100'))throw Error('Score contextual inesperado');
 checks.push('Vitrine calcula compatibilidade com clube/equipe selecionados');
 const beforeRefresh=await page.locator('#vtCompatibility [data-fit-result]').innerText();
 await page.waitForTimeout(1100);await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
 await page.waitForFunction(previous=>document.querySelector('#vtCompatibility [data-fit-result]')?.innerText!==previous,beforeRefresh);
 checks.push('Compatibilidade acompanha a atualização da Vitrine');
 await context.close();
 ({page,context}=await session(data.club));
 await page.goto(data.base+'/#/clube?clubId='+data.clubId);
 const teamForm=page.locator('form[data-resource="teams"]');await teamForm.waitFor({state:'attached'});
 await teamForm.locator('..').locator('summary').click();
 await teamForm.locator('[name="name"]').fill('Equipe de navegador');await teamForm.locator('[name="category"]').fill('SUB20');await teamForm.locator('[name="modality"]').fill('FUTEBOL');await teamForm.locator('[name="source"]').fill('Smoke de navegador');
 await teamForm.getByRole('button',{name:'Adicionar',exact:true}).click();
 await page.getByText('Equipe de navegador',{exact:true}).first().waitFor();
 checks.push('Clube cria equipe pelo formulário');
 await context.close();
 ({page,context}=await session(data.manager));
 await page.goto(data.base+'/#/manager?managerId='+data.managerId);
 await page.locator('#managerEdit').waitFor({state:'attached'});
 await page.getByText('Editar perfil de Manager',{exact:true}).click();
 await page.locator('#managerEdit [name="transferSituation"]').selectOption('LOAN_LIST');
 await page.locator('#managerEdit button[type="submit"],#managerEdit button:not([type])').last().click();
 await page.getByText('Na lista de empréstimos',{exact:false}).first().waitFor();
 checks.push('Manager edita situação de transferência');
 await page.screenshot({path:'/tmp/manager-profile-desktop.png',fullPage:true});
 await context.close();
 ({page,context}=await session(data.player,{width:390,height:844}));
 await page.goto(data.base+'/#/mercado');
 await page.locator('#playerMarket').waitFor();
 await page.locator('#playerMarket [name="transferSituation"]').selectOption('SWAP_LIST');
 await page.getByRole('button',{name:'Salvar perfil esportivo',exact:true}).click();
 await page.getByText('Perfil e disponibilidade atualizados.',{exact:true}).waitFor();
 checks.push('Jogador edita mercado em viewport móvel');
 await page.screenshot({path:'/tmp/player-market-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2);if(overflow)throw Error('Overflow horizontal na tela móvel');
 await context.close();await browser.close();
 if(errors.length)throw Error('Erros JS: '+errors.join('; '));
 console.log(JSON.stringify({passed:checks.length,checks},null,2));
})().catch(e=>{console.error(e.message);process.exit(1);});
